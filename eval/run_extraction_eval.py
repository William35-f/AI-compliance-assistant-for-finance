"""Score /extract against hand-checked values for the 5 annual reports.

Usage:  python eval/run_extraction_eval.py [--name NAME]

Per-field accuracy:
- revenue / net_profit / total_debt: correct if within 0.5% of the true full
  amount (after unit conversion). For a debt-free company (truth 0), 0 is correct.
- *_page: the cited page is one of the truth pages.
- company / fiscal_year / currency: case-insensitive match (company: one name
  contains the other's first word).
Also reports how many extracted numbers passed the code-level verification.

Results go to eval/results/<timestamp>_extraction_<name>.json and a row in
eval/results/extraction_summary.md.
"""

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

from regulens.config import RAW_DIR, get_settings
from regulens.extraction import extract_report
from regulens.llm import LLMQuotaExceeded, make_llm

EVAL_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVAL_DIR / "results"
TOLERANCE = 0.005
FIELDS = ["revenue", "net_profit", "total_debt"]


def amount_correct(predicted: float | None, truth: float) -> bool:
    if truth == 0:
        return predicted in (0, 0.0, None)
    return predicted is not None and abs(predicted - truth) / abs(truth) <= TOLERANCE


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--name", default="default")
    args = parser.parse_args()
    settings = get_settings()
    llm = make_llm(settings.gemini_model)

    truths = [
        json.loads(line)
        for line in (EVAL_DIR / "extraction_truth.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    rows, checks = [], {}
    for truth in truths:
        sid = truth["source_id"]
        try:
            result = extract_report(RAW_DIR / f"{sid}.pdf", llm, source_id=sid)
        except LLMQuotaExceeded as exc:
            print(f"Stopped: {exc}")
            return 1
        row = {
            "source_id": sid,
            "company": {"predicted": result.company, "truth": truth["company"]},
            "fiscal_year": {"predicted": result.fiscal_year, "truth": truth["fiscal_year"]},
            "currency": {"predicted": result.currency, "truth": truth["currency"]},
            "warnings": result.warnings,
            "latency_ms": result.latency_ms,
            "cost_usd": result.cost_usd,
            "key_risks": [r.title for r in result.key_risks],
        }
        for field in FIELDS:
            figure = getattr(result, field)
            row[field] = {
                "predicted": figure.value,
                "truth": truth[field]["value"],
                "page": figure.page,
                "truth_pages": truth[field]["pages"],
                "verified": figure.verified,
            }
            checks.setdefault(field, []).append(amount_correct(figure.value, truth[field]["value"]))
            page_ok = figure.page in truth[field]["pages"] or (
                truth[field]["value"] == 0 and not getattr(figure, "components", [1])
            )
            checks.setdefault(f"{field}_page", []).append(page_ok)
            checks.setdefault("verified_numbers", []).append(figure.verified)
        checks.setdefault("company", []).append(
            truth["company"].lower().split()[0] in result.company.lower()
        )
        checks.setdefault("fiscal_year", []).append(
            truth["fiscal_year"].lower() == result.fiscal_year.lower().replace(" ", "")
        )
        checks.setdefault("currency", []).append(truth["currency"] == result.currency)
        checks.setdefault("risks_found", []).append(len(result.key_risks) >= 3)
        rows.append(row)
        print(
            f"  {sid:<22} " + "  ".join(f"{f}={'ok' if checks[f][-1] else 'WRONG'}" for f in FIELDS)
        )

    accuracy = {k: round(sum(v) / len(v), 3) for k, v in checks.items()}
    timestamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    out = RESULTS_DIR / f"{timestamp}_extraction_{args.name}.json"
    out.write_text(
        json.dumps(
            {
                "timestamp": timestamp,
                "model": settings.gemini_model,
                "accuracy": accuracy,
                "reports": rows,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    summary = RESULTS_DIR / "extraction_summary.md"
    if not summary.exists():
        summary.write_text(
            "# Extraction runs\n\nGenerated by `eval/run_extraction_eval.py`.\n\n"
            "| run | model | " + " | ".join(accuracy) + " |\n"
            "|" + "---|" * (len(accuracy) + 2) + "\n",
            encoding="utf-8",
        )
    with summary.open("a", encoding="utf-8") as f:
        f.write(
            f"| {timestamp}_{args.name} | {settings.gemini_model} | "
            + " | ".join(f"{v:.2f}" for v in accuracy.values())
            + " |\n"
        )
    print("\nPer-field accuracy:")
    for key, value in accuracy.items():
        print(f"  {key:<18} {value:.2f}")
    print(f"Saved {out.relative_to(EVAL_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
